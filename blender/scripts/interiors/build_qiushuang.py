"""秋爽斋室内（第四十回；坐标与 blender/qiushuang.blend 相同，原点在院心，网页 (-86, 19)）。
用法：python3 blender/scripts/interiors/build_qiushuang.py
外壳开门：先跑 blender/scripts/sites/qiushuang_doors.py（院门拱洞、晓翠堂与三间明间的门扇已在外壳里剪去），本脚本在室内放敞开的门扇与陈设。

  第四十回：探春素喜阔朗，这三间屋子并不曾隔断。当地放着一张花梨大理石大案，案上磊着各种名人法帖，并数十方宝砚，
  各色笔筒，笔海内插的笔如树林一般。那一边设着斗大的一个汝窑花囊，插着满满的一囊水晶球儿的白菊。西墙上当中挂着
  一大幅米襄阳《烟雨图》，左右挂着一副对联，乃是颜鲁公墨迹，其词云：烟霞闲骨格，泉石野生涯。案上设着大鼎。左边
  紫檀架上放着一个大官窑的大盘，盘内盛着数十个嫩黄香橼。右边洋漆架上悬着一个白玉比目磬，旁边挂着小锤。
  地下两溜十二把四出头的楠木交椅。……东边便设着卧榻，拔步床上悬着葱绿双绣花卉草虫纱帐。
  「早饭摆在秋爽斋晓翠堂上」：晓翠堂（借怡红院正房抱厦）作宴厅，中间留空给桌案（游戏里摆桌），四周只做条案、花瓶、宫灯。

房间（Blender 坐标）：
  探春三间：x −13.37…−10.7，y −11.5…−2.5，地 z=0.57；西墙 x=−13.37，门在东面明间（y −8.52…−5.49）。
  晓翠堂：x ±7.65，y 1.8…13.09，地 z=0.81；明间（x ±1.62）抱厦前檐门扇敞开。
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from kit import Kit, new_file, save_and_export

ZW = 0.57      # 三间地
ZH = 0.81      # 晓翠堂地
new_file()
K = Kit('qiushuang')
WOOD, TAN, LI = '花梨', '紫檀', '黑漆'

# ================= 探春三间 =================
XW = -13.37          # 西墙内皮
YS, YN = -11.5, -2.5
# ---- 明间四扇门敞开，向室内折到门柱两侧（朱漆，与外壳同色） ----
for y_h, sgn in ((-8.55, 1), (-5.45, -1)):
    for k in range(2):
        with K.at(-10.66, y_h + sgn * 0.065 * k, ZW + 0.01, 180):
            K.door_leaf('朱漆', 0.76, 2.38, t=0.05)

# ---- 当地大案：花梨木，大理石面（长边顺 y，靠西墙） ----
CX = XW + 0.52
with K.at(CX, -7.0, ZW, 90):                     # 局部 x → 世界 +y；局部 +y → 世界 −x（朝墙）
    K.table(WOOD, 2.4, 0.86, 0.88, top=0.07, leg=0.09, apron=0.1)
    K.box('大理石', -1.14, -0.4, 0.88, 1.14, 0.4, 0.93)             # 大理石面
    K.box(WOOD, -1.2, -0.46, 0.86, 1.2, 0.46, 0.88)                 # 面框
    # 名人法帖：成摞
    K.books('书函', -1.12, -0.55, -0.12, 0.28, 0.93, 1.08, 1.0)
    K.books('书函黄', -0.5, -0.1, -0.06, 0.3, 0.93, 1.02, 1.0)
    # 数十方宝砚：一排排小砚
    for i in range(12):
        x = -0.55 + (i % 6) * 0.19
        y = -0.28 + (i // 6) * 0.2
        K.box('墨', x, y, 0.93, x + 0.14, y + 0.11, 0.955)
        K.box('黑漆', x + 0.01, y + 0.01, 0.955, x + 0.13, y + 0.1, 0.965)
    # 各色笔筒
    for k, (x, y, m, r, h) in enumerate(((0.1, -0.15, '青瓷', 0.06, 0.18), (0.2, 0.2, '紫砂', 0.055, 0.2), (0.3, -0.12, '青花', 0.06, 0.17), (-0.15, 0.3, '瓷白', 0.05, 0.16))):
        K.cyl(m, x, y, 0.93, 0.93 + h, r, seg=12)
        for j in range(5):
            a = j * 1.3 + k
            K.rod('竹竿', (x, y, 0.93 + h - 0.03), (x + 0.03 * math.cos(a), y + 0.03 * math.sin(a), 0.93 + h + 0.12 + 0.03 * (j % 3)), 0.004, seg=4)
    # 笔海：大海碗似的，笔如树林
    K.lathe('青花', 0.48, 0.2, 0.93, [(0.1, 0), (0.14, 0.06), (0.15, 0.2), (0.13, 0.26), (0.0, 0.26)], seg=16)
    for j in range(26):
        a = j * 2.399
        rr = 0.075 * math.sqrt((j + 1) / 26)
        K.rod('竹竿', (0.48 + rr * math.cos(a), 0.2 + rr * math.sin(a), 1.12), (0.48 + 2.2 * rr * math.cos(a), 0.2 + 2.2 * rr * math.sin(a), 1.4 + 0.1 * (j % 4)), 0.0045, seg=4)
        K.sph('紫檀', 0.48 + 2.2 * rr * math.cos(a), 0.2 + 2.2 * rr * math.sin(a), 1.4 + 0.1 * (j % 4), 0.006, 0.006, 0.01, seg=4)
    # 案上大鼎
    K.ding('铜', 0.0, 0.1, 0.93, 0.36)
    # 那一边：斗大的汝窑花囊，插着满满一囊水晶球儿的白菊
    K.vase('青瓷', 0.98, -0.05, 0.93, 0.32, 'guan', flowers=22, fcol='花白')
    K.col(-1.2, -0.46, 0, 1.2, 0.46, 0.93)

# ---- 西墙：米襄阳《烟雨图》居中，左右颜鲁公对联 ----
with K.at(XW + 0.02, -7.0, 0, 90):
    K.scroll(0, 0, 3.55, 1.5, 2.0, face=-1, paint='烟雨图')
    K.scroll(-1.35, 0, 3.5, 0.34, 1.9, face=-1, paint='颜联上')
    K.scroll(1.35, 0, 3.5, 0.34, 1.9, face=-1, paint='颜联下')

# ---- 左边（南）紫檀架：大官窑大盘，盘内数十个嫩黄香橼 ----
with K.at(XW + 0.3, -9.35, ZW, 90):
    for sx in (-1, 1):
        for sy in (-1, 1):
            K.box(TAN, sx * 0.34 - 0.025, sy * 0.15 - 0.025, 0, sx * 0.34 + 0.025, sy * 0.15 + 0.025, 1.18)
    for z in (0.18, 0.62, 1.15):
        K.box(TAN, -0.38, -0.19, z, 0.38, 0.19, z + 0.035)
    K.box(TAN, -0.38, -0.19, 1.18, 0.38, -0.16, 1.24)               # 帽
    K.lathe('青瓷', 0.0, 0.0, 1.185, [(0.14, 0), (0.24, 0.015), (0.3, 0.05), (0.32, 0.06), (0.3, 0.065), (0.0, 0.03)], seg=20)   # 官窑大盘
    import random as _r
    rr = _r.Random(7)
    for i in range(30):
        a = rr.uniform(0, 6.283)
        d = 0.16 * math.sqrt(rr.random())
        z = 1.2 + 0.04 * (1 - d / 0.2) + rr.uniform(0, 0.05) + (0.045 if d < 0.1 else 0)
        K.sph('菊黄', d * math.cos(a), d * math.sin(a), z + 0.04, 0.04, 0.04, 0.05, seg=8)   # 嫩黄香橼
    K.col(-0.38, -0.19, 0, 0.38, 0.19, 1.3)

# ---- 右边（北）洋漆架：白玉比目磬，旁边挂着小锤 ----
with K.at(XW + 0.3, -4.75, ZW, 90):
    for sx in (-1, 1):
        K.box(LI, sx * 0.36 - 0.03, -0.12, 0, sx * 0.36 + 0.03, 0.12, 1.55)
        K.box('描金', sx * 0.36 - 0.032, -0.125, 1.5, sx * 0.36 + 0.032, 0.125, 1.54)
        K.box(LI, sx * 0.36 - 0.07, -0.18, 0, sx * 0.36 + 0.07, 0.18, 0.06)
    K.box(LI, -0.4, -0.04, 1.5, 0.4, 0.04, 1.56)
    K.box('描金', -0.4, -0.045, 1.54, 0.4, 0.045, 1.56)
    # 磬：两片白玉叠成比目（鱼形扁板），丝绦挂在横梁
    for dy in (-0.03, 0.03):
        K.sph('玉', 0.0, dy, 1.1, 0.24, 0.012, 0.19, seg=14)
    K.rod('锦缎', (-0.12, 0, 1.5), (-0.12, 0, 1.25), 0.007, seg=4)
    K.rod('锦缎', (0.12, 0, 1.5), (0.12, 0, 1.25), 0.007, seg=4)
    # 小锤
    K.rod('紫檀', (0.3, 0.0, 1.5), (0.3, 0.0, 1.1), 0.005, seg=4)
    K.sph('紫檀', 0.3, 0.0, 1.08, 0.025, 0.025, 0.025, seg=8)
    K.col(-0.42, -0.2, 0, 0.42, 0.2, 1.58)

# ---- 东边卧榻：拔步床，悬着葱绿双绣花卉草虫纱帐（靠北端西墙） ----
with K.at(XW + 0.78, -3.36, ZW, 90):
    K.bed(WOOD, w=1.9, d=1.55, H=2.3, curtain='葱绿纱', quilt='素绸', pillow='锦缎黄', frieze=WOOD)

# ---- 地下的楠木四出头交椅（东墙边，门两侧各三把，面朝西） ----
for y in (-11.0, -10.2, -9.4, -4.65, -3.85, -3.05):
    with K.at(-11.25, y, ZW, 90):
        K.chair('楠木', 'guanmao', cushion=None)
K.lantern(-11.9, -7.0, 3.6, drop=0.6)
K.lantern(-11.9, -10.2, 3.6, drop=0.6)
K.lantern(-11.9, -3.9, 3.6, drop=0.6)

# ================= 晓翠堂 =================
# ---- 地：金砖 ----
K.box('金砖', -7.6, 1.9, ZH, 7.6, 13.08, ZH + 0.012)
# ---- 明间四扇门敞开，向室内（+y）折到门柱两侧 ----
for x_h, sgn in ((-1.64, 1), (1.64, -1)):
    for k in range(2):
        with K.at(x_h + sgn * 0.065 * k, 2.86, 0.96, 90):
            K.door_leaf('朱漆', 0.78, 2.1, t=0.05)
# ---- 后墙：条案、双瓶、香鼎，上悬横披 ----
with K.at(0, 12.72, ZH):
    K.qiaotou(WOOD, 3.0, 0.52, 0.9)
    K.vase('青花', -1.0, 0.0, 0.9, 0.46, 'meiping', flowers=10, fcol='菊黄')
    K.vase('青花', 1.0, 0.0, 0.9, 0.46, 'meiping', flowers=10, fcol='花白')
    K.ding('铜', 0.0, 0.0, 0.9, 0.34)
K.scroll(0, 13.05, 4.55, 2.2, 1.0, face=-1, paint='晓翠堂横披')
# ---- 两山墙：长案 + 花瓶 + 对称灯 ----
for sx in (-1, 1):
    with K.at(sx * 7.3, 8.0, ZH, 90 if sx < 0 else -90):
        K.qiaotou(WOOD, 2.2, 0.46, 0.88)
        K.vase('青瓷', 0.0, 0.0, 0.88, 0.4, 'gu', flowers=6, fcol='花红')
        K.vase('瓷白', 0.7, 0.0, 0.88, 0.3, 'guan')
# 两山墙边对椅：每侧两把椅子夹一只茶几（朝向厅心）
for sx in (-1, 1):
    for y in (6.3, 9.7):
        with K.at(sx * 6.55, y, ZH, 90 if sx < 0 else -90):
            K.chair(WOOD, 'guanmao', cushion='锦缎')
    with K.at(sx * 6.55, 8.0, ZH):
        K.table(WOOD, 0.5, 0.5, 0.72, top=0.04, leg=0.05, apron=0.06)
        K.teaset(0, 0, 0.72)
for x, y in ((-3.2, 7.8), (3.2, 7.8), (-3.2, 11.0), (3.2, 11.0), (0.0, 4.2)):
    K.lantern(x, y, 5.25, drop=0.9)

save_and_export(K)
