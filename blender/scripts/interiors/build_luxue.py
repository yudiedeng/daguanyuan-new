"""芦雪广室内（第四十九、五十回；坐标与 blender/luxue.blend 相同）。
用法：flock /tmp/coljson.lock python3 blender/scripts/interiors/build_luxue.py
外壳开门：先跑 blender/scripts/sites/luxue_doors.py（明间板门已剪去），本脚本放敞开的门扇与陈设。

  「那广就在傍山临水河滩之上，一带几间，茅檐土壁，槿篱竹牖，推窗便可垂钓，四面都是芦苇掩覆。」
  雪天联诗在「地炕屋内」：西两间砌地炕（低炕台铺红毡），炕桌上笔砚纸墨、香（李纨出题限韵）；
  湘云宝玉在外头烤鹿肉——「铁炉、铁叉、铁丝蒙」：铁炉（Tripo）放前檐下明间东侧；
  明间后墙（临水小窗）旁插红梅的大瓶（Tripo，宝玉乞红梅）；东头竹椅方桌、矮凳；炭盆；
  蓑衣斗笠挂东山墙；前窗挂竹帘；钓竿靠后窗。质朴：竹、木本色、土墙。

房间（Blender 坐标）：x −7.37…7.37，y −2.65…3.05，地 z=0.35（夯土面 0.362）；前墙 y≈−2.8，门洞 x ±0.75（0.47…2.48）；
  后墙 y≈3.2，明间小窗 x ±0.4（1.75…2.45）；前檐廊 y −4.04…−2.95，地 0.35。
Tripo 占位块：材质一律 'TRIPO占位'，带碰撞。
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from kit import Kit, new_file, save_and_export

new_file()
K = Kit('luxue')
Z0 = 0.35
ZF = 0.362
XW, XE, YF, YB = -7.37, 7.37, -2.65, 3.05
WOOD, BAM, OLD = '本色木', '黄竹', '旧木'
TRIPO = []


def tripo(name, cx, cy, z0, sx, sy, sz, face):
    K.box('TRIPO占位', cx - sx / 2, cy - sy / 2, z0, cx + sx / 2, cy + sy / 2, z0 + sz, col=True)
    TRIPO.append((name, round(cx, 2), round(cy, 2), round(z0, 3), sx, sy, sz, face))


K.box('夯土地', XW, YF, Z0, XE, YB, ZF)

# ---- 明间板门两扇，向内敞开贴门洞两侧 ----
for x_h, sgn in ((-0.73, 1), (0.73, -1)):
    with K.at(x_h, -2.62, Z0 + 0.12, 90):
        # 局部 x 0…0.7 → 世界 +y；局部 y → 世界 −x
        for i in range(4):
            K.box(OLD, 0.01 + i * 0.172, 0.025 * sgn - 0.02, 0, 0.17 + i * 0.172, 0.025 * sgn + 0.02, 2.0)
        for z in (0.3, 0.95, 1.65):
            K.box('旧木', 0.04, 0.07 * sgn - 0.025, z, 0.66, 0.07 * sgn + 0.025, z + 0.1)
# 门上卷起的竹帘
with K.at(0, -2.58, 2.4, 0):
    K.rod('YZ_湘帘', (-0.75, 0, 0), (0.75, 0, 0), 0.05, seg=8)
    for sx in (-1, 1):
        K.rod('麻绳', (sx * 0.5, 0.02, 0.06), (sx * 0.5, 0.02, -0.08), 0.006, seg=4)

# ================= 西两间：地炕 =================
KX0, KX1, KY0, KY1, KH = XW, -2.9, -1.0, YB, 0.42
K.box('青砖', KX0, KY0, ZF, KX1, KY1, ZF + KH - 0.05)
K.box(WOOD, KX0, KY0 - 0.06, ZF + KH - 0.08, KX1 + 0.06, KY0 + 0.06, ZF + KH)          # 炕沿
K.box(WOOD, KX1 - 0.06, KY0, ZF + KH - 0.08, KX1 + 0.06, KY1, ZF + KH)
K.box('蒲席', KX0, KY0 + 0.06, ZF + KH - 0.05, KX1 - 0.06, KY1, ZF + KH - 0.02)
K.box('红毡', KX0 + 0.1, KY0 + 0.15, ZF + KH - 0.02, KX1 - 0.15, KY1 - 0.1, ZF + KH)   # 铺毡
K.col(KX0, KY0 - 0.06, ZF, KX1 + 0.06, KY1, ZF + KH)                                       # 炕台（可踏上）
# 灶口（炕前烧火口）
K.box('炭', -5.4, KY0 - 0.065, ZF + 0.06, -4.9, KY0 - 0.06, ZF + 0.26)
ZK = ZF + KH
# 两张炕桌：李纨出题限韵——笔砚纸墨、香
for cx, cy, main in ((-5.6, 1.0, True), (-3.9, 1.6, False)):
    with K.at(cx, cy, ZK):
        K.table(OLD, 1.0, 0.62, 0.32, top=0.03, leg=0.04, apron=0.05, col=False)
        if main:
            K.study_set(0.1, 0.0, 0.32)
            K.box('画心', -0.45, 0.12, 0.32, -0.15, 0.28, 0.326)             # 题纸
            K.lathe('铜', 0.38, 0.18, 0.32, [(0.04, 0), (0.06, 0.02), (0.06, 0.06), (0.05, 0.07)], seg=10)   # 香炉
            for k in range(3):
                K.rod('朱漆', (0.38 + 0.01 * k, 0.18, 0.37), (0.38 + 0.012 * k, 0.18, 0.55), 0.002, seg=3)        # 线香
        else:
            K.study_set(0.0, 0.0, 0.32, rot=180)
            K.teaset(0.35, 0.15, 0.32, m='陶', cups=3)
    K.col(cx - 0.5, cy - 0.31, ZK, cx + 0.5, cy + 0.31, ZK + 0.33)
# 坐褥
for cx, cy in ((-6.5, 1.0), (-4.7, 1.0), (-5.6, 0.0), (-5.6, 2.15), (-3.9, 0.7), (-3.9, 2.6)):
    K.box('青布', cx - 0.3, cy - 0.28, ZK, cx + 0.3, cy + 0.28, ZK + 0.06)
# 炕头靠墙：被褥一摞、引枕
K.box('粗布', -7.3, -0.8, ZK, -6.7, 0.2, ZK + 0.22)
K.box('青布', -7.28, -0.75, ZK + 0.22, -6.72, 0.15, ZK + 0.3)
with K.at(-6.9, 2.75, ZK + 0.12, 0):
    K.rod('青布', (-0.25, 0, 0), (0.25, 0, 0), 0.11, seg=10)

# ---- 炭盆：炕前 ----
CX, CY = -2.2, -0.3
K.lathe(OLD, CX, CY, ZF, [(0.24, 0), (0.24, 0.04), (0.18, 0.06), (0.18, 0.2), (0.3, 0.22), (0.3, 0.26)], seg=8)   # 木架
K.lathe('铁', CX, CY, ZF + 0.24, [(0.12, 0), (0.26, 0.05), (0.29, 0.16), (0.27, 0.17)], seg=16)                     # 盆
K.lathe('炭', CX, CY, ZF + 0.33, [(0.25, 0), (0.0, 0.05)], seg=12)
for i in range(5):
    a = i * 1.26
    K.sph('花红', CX + 0.12 * math.cos(a), CY + 0.12 * math.sin(a), ZF + 0.37, 0.05, 0.05, 0.025, seg=6)            # 红炭
K.col(CX - 0.3, CY - 0.3, ZF, CX + 0.3, CY + 0.3, ZF + 0.42)
# 矮凳两只（炭盆边）
for x, y in ((-1.5, -0.1), (-2.2, 0.55)):
    with K.at(x, y, ZF):
        K.table(WOOD, 0.4, 0.26, 0.28, top=0.03, leg=0.035, apron=0.03, col=True, horse=False)

# ================= 明间：红梅大瓶（Tripo）、钓竿 =================
tripo('红梅大瓶', 1.0, 2.62, ZF, 0.6, 0.6, 1.7, '-Y')
# 钓竿靠后窗西侧
for k in range(3):
    K.rod('竹竿', (-0.8 - 0.12 * k, 2.92, ZF), (-0.62 - 0.1 * k, 3.02, 2.9 - 0.2 * k), 0.012 - 0.002 * k, seg=5)
K.rod('麻绳', (-0.62, 3.0, 2.9), (-0.66, 2.98, 1.6), 0.002, seg=3)
K.col(-1.15, 2.8, ZF, -0.55, 3.05, ZF + 2.4)
# 鱼篓
K.lathe(BAM, -1.4, 2.8, ZF, [(0.12, 0), (0.18, 0.12), (0.17, 0.26), (0.1, 0.34), (0.11, 0.38)], seg=10)

# ================= 东两间：竹椅方桌、竹帘、蓑衣斗笠 =================
with K.at(4.6, 0.6, ZF):
    K.table(BAM, 0.9, 0.9, 0.78, top=0.04, leg=0.045, apron=0.05, stretch=True)
    K.teaset(0.0, 0.0, 0.78, m='陶', cups=4)
for (x, y, r) in ((4.6, 1.45, 0), (4.6, -0.25, 180), (5.45, 0.6, -90), (3.75, 0.6, 90)):
    with K.at(x, y, ZF, r):
        K.chair(BAM, 'quan', cushion='粗布')
# 东头靠后墙：竹几、瓦盆、笔墨（题诗用）
with K.at(6.4, 2.75, ZF):
    K.table(BAM, 1.4, 0.45, 0.8, top=0.03, leg=0.04, apron=0.05)
    K.vase('陶', -0.4, 0, 0.8, 0.3, 'guan')
    K.books('书函', 0.0, 0.6, -0.15, 0.15, 0.8, 0.95, 1.0)
# 矮凳
for x, y in ((6.6, -1.6), (2.4, 2.6)):
    with K.at(x, y, ZF):
        K.table(WOOD, 0.4, 0.26, 0.3, top=0.03, leg=0.035, apron=0.03, col=True, horse=False)
# 蓑衣、斗笠挂东山墙（x≈7.37）
for y in (-0.9, 0.9):
    K.box(OLD, 7.3, y - 0.03, 2.3, 7.37, y + 0.03, 2.36)                      # 木橛
    # 蓑衣：上窄下宽的草片，三层
    for k in range(3):
        w0, w1 = 0.22 + k * 0.08, 0.38 + k * 0.1
        z1, z0 = 2.28 - k * 0.3, 1.86 - k * 0.32
        K.bar('稻草', (7.3 - 0.02 * k, y, z1), (7.32 - 0.02 * k - 0.02, y, z0), (w0 + w1), 0.04)
    # 斗笠
    K.lathe(BAM, 7.12, y, 2.38, [(0.34, 0), (0.3, 0.04), (0.04, 0.2), (0.0, 0.22)], seg=14)
    K.col(7.0, y - 0.45, 1.0, 7.37, y + 0.45, 2.6)

# ---- 前窗竹帘（四樘窗，半卷） ----
for xc in (-6.0, -3.0, 3.0, 6.0):
    K.box('YZ_湘帘', xc - 0.52, -2.62, 1.95, xc + 0.52, -2.6, 2.42)
    K.rod('YZ_湘帘', (xc - 0.54, -2.59, 1.93), (xc + 0.54, -2.59, 1.93), 0.035, seg=8)
    for sx in (-1, 1):
        K.rod('麻绳', (xc + sx * 0.35, -2.58, 2.44), (xc + sx * 0.35, -2.58, 1.9), 0.004, seg=3)
# 后窗竹帘（卷起）
K.rod('YZ_湘帘', (-0.45, 3.02, 2.45), (0.45, 3.02, 2.45), 0.04, seg=8)

# ---- 灯：炕头一盏、东头一盏 ----
K.candle_stand(-3.25, -0.6, ZF, h=1.3)
K.col(-3.43, -0.78, ZF, -3.07, -0.42, ZF + 1.3)
K.candle_stand(3.4, 2.7, ZF, h=1.3)
K.col(3.22, 2.52, ZF, 3.58, 2.88, ZF + 1.3)

# ================= 前檐下：铁炉（Tripo）烤鹿肉 =================
tripo('铁炉', 2.75, -3.5, Z0, 0.8, 0.5, 0.72, '-Y')
# 铁叉两把靠墙、炭篓、矮凳
for k in range(2):
    x = 3.45 + k * 0.12
    K.rod('铁', (x, -3.05, Z0), (x + 0.05, -2.97, Z0 + 1.35), 0.01, seg=4)
    for t in (-0.04, 0.0, 0.04):
        K.rod('铁', (x + 0.05 + t, -2.97, Z0 + 1.35), (x + 0.05 + t, -2.96, Z0 + 1.5), 0.005, seg=3)
K.lathe(BAM, 1.9, -3.55, Z0, [(0.14, 0), (0.18, 0.1), (0.18, 0.3), (0.15, 0.34)], seg=10)
K.lathe('炭', 1.9, -3.55, Z0 + 0.3, [(0.15, 0), (0.0, 0.06)], seg=10)
K.col(1.72, -3.73, Z0, 2.08, -3.37, Z0 + 0.36)
with K.at(3.95, -3.55, Z0):
    K.table(WOOD, 0.4, 0.26, 0.3, top=0.03, leg=0.035, apron=0.03, col=True, horse=False)

for t in TRIPO:
    print('TRIPO', t)
save_and_export(K)
