def tripo(name, cx, cy, z0, sx, sy, sz, face, desc):
    """Tripo 占位块：中心 (cx,cy)、底 z0、尺寸 sx×sy×sz（Blender 世界坐标，不受 K.at 影响时调用）。"""
    K.box('TRIPO占位', cx - sx / 2, cy - sy / 2, z0, cx + sx / 2, cy + sy / 2, z0 + sz, col=True)
    TRIPO.append(dict(name='TRIPO_' + name, center=[round(cx, 3), round(cy, 3)], bottom_z=round(z0, 3),
                      size=[sx, sy, sz], front=face, prompt=desc))


def putuan(x, y, z, r=0.26):
    """蒲团：蒲草编的扁圆垫（矮，可跨过，不设碰撞）。"""
    K.lathe('蒲席', x, y, z, [(r * 0.85, 0), (r, 0.03), (r, 0.08), (r * 0.85, 0.11), (0.0, 0.12)], seg=18)


def candle(x, y, z, h=0.34):
    """烛台：铜灯座 + 红烛。"""
    K.lathe('铜', x, y, z, [(0.07, 0), (0.07, 0.015), (0.02, 0.04), (0.015, h - 0.05), (0.06, h - 0.03), (0.06, h - 0.015), (0.0, h - 0.015)], seg=10)
    K.cyl('花红', x, y, z + h - 0.015, z + h + 0.12, 0.018, seg=8)
    K.cyl('烛', x, y, z + h + 0.12, z + h + 0.145, 0.006, seg=4)


def plum(x, y, z, h=0.42, n=9):
    """瓶供红梅：瓶 + 枝干 + 花朵（第四十九/五十回栊翠庵红梅，此处先供上）。"""
    K.vase('青瓷', x, y, z, h, 'meiping')
    r = K.rng
    top = z + h
    for i in range(n):
        a = r.uniform(0, 2 * math.pi); L = r.uniform(0.35, 0.7)
        mid = (x + math.cos(a) * L * 0.25, y + math.sin(a) * L * 0.25, top + L * 0.5)
        tip = (x + math.cos(a + 0.4) * L * 0.55, y + math.sin(a + 0.4) * L * 0.55, top + L)
        K.rod('旧木', (x, y, top - 0.05), mid, 0.008, seg=4)
        K.rod('旧木', mid, tip, 0.005, seg=4)
        for k in range(5):
            f = 0.35 + 0.15 * k
            p = (mid[0] + (tip[0] - mid[0]) * f, mid[1] + (tip[1] - mid[1]) * f, mid[2] + (tip[2] - mid[2]) * f)
            K.sph('花红', p[0] + r.uniform(-0.03, 0.03), p[1] + r.uniform(-0.03, 0.03), p[2], 0.022, seg=6)


def banner(x, y, ztop, L=2.5, w=0.32, m='锦缎黄'):
    """经幡：顶上横杆，长条幡身，下垂三条飘带。"""
