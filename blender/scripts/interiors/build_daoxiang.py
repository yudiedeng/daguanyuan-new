"""稻香村正房室内（第十七回、第四回）。
用法：python3 blender/scripts/interiors/build_daoxiang.py

  第十七回：里面纸窗木榻，富贵气象一洗皆尽。
  第四回：（李纨）只以侍亲养子，外则陪侍小姑等针黹诵读而已。

茅屋正房（Blender 坐标）：五间，柱 x=−11.4、−8.5、−5.5、−2.5、0.5、3.4；黄泥前墙 y≈12.3、后墙 y≈18.3；
室内 x −11.37…3.37、y 12.45…18.15，地坪取前檐石台面 z=0.50；明间柴门 x −4.75…−3.25（glb_cut 剪去，此处做成敞开）。
布置：明间木榻；西两间卧房（布帐木床、衣箱、纺车针线）；东两间教子读书（书案、竹书架），壁上挂蓑衣斗笠锄头，墙角米缸酒坛。
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from kit import Kit, new_file, save_and_export

Z0 = 0.50
XW, XE, YF, YB = -11.37, 3.37, 12.45, 18.15
new_file()
K = Kit('daoxiang')
WOOD = '本色木'

K.box('夯土地', XW, YF, Z0 - 0.05, XE, YB, Z0)

# ---- 柴门：两扇木板门向内敞开 ----
for sx, hx in ((-1, -4.72), (1, -3.28)):
    with K.at(hx, 12.5, Z0, 90 if sx < 0 else 90):
        x0, x1 = (0, 0.7)
        K.box(WOOD, x0, -0.025, 0.02, x1, 0.025, 2.05)
        for z in (0.25, 1.0, 1.75):
            K.box('旧木', x0 + 0.04, 0.025, z, x1 - 0.04, 0.05, z + 0.1)
        K.bar('旧木', (x0 + 0.08, 0.04, 0.3), (x1 - 0.08, 0.04, 1.75), 0.06, 0.03)

# ---- 明间：木榻 ----
with K.at(-4.0, 17.65, Z0):
    K.kang(WOOD, 2.2, 0.85, mat_cushion='蒲席', back=0.35)
    with K.at(0, 0.02, 0.45 + 0.06 + 0.3):
        K.teaset(0.1, 0.0, 0, m='陶', cups=2)
for sx in (-1, 1):
    with K.at(-4.0 + sx * 0.9, 16.4, Z0):
        K.table(WOOD, 0.36, 0.36, 0.45, top=0.04, leg=0.04, apron=0.04)      # 方凳
K.candle_stand(-5.1, 17.6, Z0, h=1.2)
K.scroll(-4.0, YB - 0.01, Z0 + 2.85, 0.9, 1.7, face=-1, paint='画心')          # 一轴清淡山水

# ---- 西间（x −11.37…−5.5）：卧房 ----
with K.at(-5.5, (YF + YB) / 2, Z0, -90):          # 板槅：正面朝西，门靠前檐
    K.lattice_partition(WOOD, YB - YF, 2.75, paper='窗纸', door=(1.6, 2.6))
with K.at(XW + 0.78, 16.2, Z0, 90):
    K.bed(WOOD, w=2.1, d=1.45, H=2.2, curtain='粗布', quilt='青布', pillow='粗布', frieze=WOOD)
with K.at(XW + 0.4, 13.3, Z0, 90):                 # 衣箱两只叠放
    K.box('旧木', -0.45, -0.3, 0.0, 0.45, 0.3, 0.45, col=True)
    K.box('旧木', -0.4, -0.27, 0.45, 0.4, 0.27, 0.8)
    K.box('铜', -0.06, -0.31, 0.6, 0.06, -0.29, 0.68)
# 纺车：大轮 + 锭子
with K.at(-7.8, 13.6, Z0):
    K.box(WOOD, -0.6, -0.15, 0.0, 0.6, 0.15, 0.08, col=True)
    for sy in (-1, 1):
        K.bar(WOOD, (0.25, sy * 0.1, 0.08), (0.25, sy * 0.1, 0.62), 0.04, 0.04)
    R = 0.42
    for i in range(16):
        a0, a1 = 2 * math.pi * i / 16, 2 * math.pi * (i + 1) / 16
        for sy in (-1, 1):
            K.rod(WOOD, (0.25 + R * math.cos(a0), sy * 0.08, 0.62 + R * math.sin(a0)), (0.25 + R * math.cos(a1), sy * 0.08, 0.62 + R * math.sin(a1)), 0.012, seg=4)
        K.rod(WOOD, (0.25, 0, 0.62), (0.25 + R * math.cos(a0), 0.08 * (1 if i % 2 else -1), 0.62 + R * math.sin(a0)), 0.008, seg=4)
    K.rod('旧木', (-0.5, 0, 0.08), (-0.5, 0, 0.35), 0.02, seg=6)
    K.rod('素绸', (-0.55, 0, 0.36), (-0.25, 0, 0.36), 0.02, seg=6)              # 锭上的线
    K.col(-0.6, -0.2, 0, 0.75, 0.2, 1.1)
with K.at(-9.7, 13.1, Z0):                         # 针线笸箩
    K.table(WOOD, 0.7, 0.45, 0.72)
    K.lathe('藤编', 0, 0, 0.72, [(0.14, 0), (0.18, 0.08), (0.19, 0.1)], seg=16, cap=False)
    K.lathe('藤编', 0, 0, 0.72, [(0.14, 0.0), (0.0, 0.0)], seg=16)
    K.sph('锦缎', 0.05, 0.02, 0.77, 0.05, seg=8)
    K.sph('素绸', -0.06, -0.03, 0.76, 0.04, seg=8)

# ---- 东间（x −2.5…3.37）：教子读书 ----
with K.at(-2.5, (YF + YB) / 2, Z0, 90):
    K.luodizhao(WOOD, YB - YF, 2.85, shape='arch', t=0.06, carve=False)
with K.at(0.6, 15.6, Z0):
    K.table(WOOD, 1.5, 0.65, 0.8)
    K.study_set(0.1, 0.0, 0.8)
    K.books('书函', -0.7, -0.35, -0.2, 0.15, 0.8, 1.1, 1.0)
with K.at(0.6, 16.35, Z0, 180):
    K.chair(WOOD, 'guanmao', cushion='粗布')
with K.at(0.6, 14.85, Z0):
    K.table(WOOD, 0.36, 0.36, 0.45, top=0.04, leg=0.04, apron=0.04)          # 贾兰的小凳
with K.at(2.3, YB - 0.24, Z0):
    K.shelf('竹竿', 1.3, 0.38, 2.0, rows=4, fill=0.8)
# 东山墙：蓑衣、斗笠、锄头
with K.at(XE - 0.03, 15.0, Z0 + 1.0, -90):
    K.lathe('稻草', 0, 0.06, 0.0, [(0.42, 0), (0.3, 0.6), (0.14, 1.0), (0.05, 1.1)], seg=10)   # 蓑衣
    K.lathe('竹竿', 0.9, 0.06, 1.0, [(0.32, 0), (0.0, 0.18)], seg=14)                          # 斗笠
    K.rod('旧木', (-0.9, 0.04, -0.2), (-0.9, 0.04, 1.3), 0.02, seg=6)                           # 锄柄
    K.box('铁', -1.0, 0.02, -0.28, -0.8, 0.07, -0.2)
    K.col(-1.1, 0, -1.0, 1.3, 0.5, 1.2)
# 墙角：米缸、酒坛
with K.at(2.75, 13.1, Z0):
    K.lathe('陶', 0, 0, 0, [(0.2, 0), (0.3, 0.2), (0.32, 0.4), (0.26, 0.62), (0.25, 0.66)], seg=16)
    K.lathe('竹竿', 0, 0, 0.66, [(0.27, 0), (0.0, 0.03)], seg=16)                              # 缸盖
    K.col(-0.33, -0.33, 0, 0.33, 0.33, 0.7)
for i, (x, y) in enumerate(((1.9, 12.85), (1.5, 13.0))):
    with K.at(x, y, Z0):
        K.lathe('陶', 0, 0, 0, [(0.1, 0), (0.18, 0.12), (0.19, 0.28), (0.1, 0.42), (0.07, 0.45)], seg=14)
        K.sph('红毡', 0, 0, 0.47, 0.08, 0.08, 0.04, seg=8)                                       # 红布封口
        K.col(-0.2, -0.2, 0, 0.2, 0.2, 0.5)
K.candle_stand(-1.9, 13.0, Z0, h=1.2)

# ---- 外壳碰撞 ----
W = [
    [XW, YF, -0.5, XE, YB, Z0, False],                        # 地坪（可走）
    [-11.9, 12.1, Z0, -4.76, 12.5, 3.4, False],               # 前墙（留门）
    [-3.24, 12.1, Z0, 3.9, 12.5, 3.4, False],
    [-4.76, 12.1, Z0 + 2.1, -3.24, 12.5, 3.4, False],         # 门上
    [-11.9, 18.1, Z0, 3.9, 18.5, 3.4, False],                 # 后墙
    [-11.9, 12.1, Z0, XW, 18.5, 5.5, False],                  # 山墙
    [XE, 12.1, Z0, 3.9, 18.5, 5.5, False],
    [-11.9, 12.1, 3.4, 3.9, 13.6, 4.0, False],                # 坡顶（挡相机，分三段）
    [-11.9, 13.6, 4.0, 3.9, 16.9, 4.6, False],
    [-11.9, 16.9, 3.4, 3.9, 18.5, 4.0, False],
]


def solid(b):
    lx, lz, hx, hz, top, bot = b
    return abs(lx + 4) < 0.5 and -15.8 < lz < -14 and hx > 6 and hz > 2.5 and top > 0.6   # 正房实心块、台基块、窗台块


save_and_export(K, shell_cols_filter=solid, extra_cols=W)
